import {test,expect} from '@playwright/test';
import {unlockSealed,forget} from '../core/crypto';
import fs from 'node:fs/promises';
const password='Mein sicheres Kennwort Grüße 123';
test('mobile vault persists only ciphertext, locks previews and reopens with password',async({page})=>{
  await page.setViewportSize({width:412,height:915});
  await page.goto('/?mobile=1');
  await page.getByRole('button',{name:'Tresor erstellen',exact:true}).click();
  await page.getByLabel('Kennwort',{exact:true}).fill(password);
  await page.getByLabel('Kennwort bestätigen').fill(password);
  await page.getByRole('button',{name:'Schutz aktivieren',exact:true}).click();
  await expect(page.getByRole('button',{name:'Neues Dokument',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Neues Dokument',exact:true}).click();
  await page.getByLabel('Dokumenttitel',{exact:true}).fill('Geheimer Titel Grüße');
  await page.getByRole('textbox',{name:'Geschütztes Dokument bearbeiten'}).fill('Streng vertraulicher Text über Köln und die Straße.');
  await expect(page.getByRole('status')).toContainText('Verschlüsselt gespeichert');
  const sealed=await page.evaluate(()=>localStorage.getItem('writely.sealed.workspace.v1'));
  expect(sealed).not.toContain('Geheimer Titel');expect(sealed).not.toContain('vertraulicher Text');
  const snapshot=await unlockSealed(sealed!,password);
  expect((snapshot.payload as any).documents[0].document.title).toBe('Geheimer Titel Grüße');forget(snapshot);
  await page.getByRole('button',{name:'Dokumentaktionen',exact:true}).click();await page.getByRole('button',{name:'Jetzt sperren',exact:true}).click();
  await expect(page.getByRole('button',{name:'Tresor entsperren',exact:true})).toBeVisible();
  await expect(page.getByRole('textbox',{name:'Geschütztes Dokument bearbeiten'})).toHaveCount(0);
  expect(await page.locator('body').innerText()).not.toContain('Geheimer Titel');
  await page.getByRole('button',{name:'Tresor entsperren',exact:true}).click();
  await page.getByLabel('Kennwort',{exact:true}).fill('Falsches Kennwort');
  await page.getByRole('button',{name:'Entsperren',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('Entsperren fehlgeschlagen');
  await page.getByLabel('Kennwort',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Entsperren',exact:true}).click();
  await expect(page.locator('.secure-card')).toContainText('Geheimer Titel Grüße');
  const leaked=await page.evaluate(()=>Object.entries(localStorage).filter(([key])=>!key.startsWith('writely.sealed.')).map(([,v])=>v).join(''));
  expect(leaked).not.toContain('vertraulicher Text');
  await fs.mkdir('work/cross-platform',{recursive:true});await page.screenshot({path:'work/cross-platform/android-phone.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
test('Node fixture opens in Chromium, preserves tables, images and notes after browser save',async({page})=>{
  const fixture=await fs.readFile('tests/fixtures/sealed-v1.writely','utf8');
  await page.goto('/?mobile=1');
  await page.evaluate(text=>localStorage.setItem('writely.sealed.workspace.v1',text),fixture);await page.reload();
  await page.getByRole('button',{name:'Tresor entsperren',exact:true}).click();
  await page.getByLabel('Kennwort',{exact:true}).fill('Writely Testvektor Grüße 2026');
  await page.getByRole('button',{name:'Entsperren',exact:true}).click();
  await page.locator('.secure-card-open').click();
  await expect(page.locator('.secure-prose table')).toBeVisible();await expect(page.getByRole('img',{name:'Testbild'})).toBeVisible();
  await page.getByLabel('Dokumenttitel',{exact:true}).fill('Zurück nach Windows');
  await page.locator('.secure-prose > p').first().click();await page.keyboard.press('End');await page.keyboard.type(' · zurück gespeichert');
  await expect(page.getByRole('status')).toContainText('Verschlüsselt gespeichert');
  const text=await page.evaluate(()=>localStorage.getItem('writely.sealed.workspace.v1'));
  const result=await unlockSealed(text!,'Writely Testvektor Grüße 2026');
  const d=(result.payload as any).documents[0].document;
  expect(d.title).toBe('Zurück nach Windows');expect(d.content.content.some((n:any)=>n.type==='table')).toBe(true);expect(d.content.content.some((n:any)=>n.type==='image')).toBe(true);
  expect(JSON.stringify(d.content)).toContain('Interoperable Notiz');forget(result);
});
test('background lock cancels an in-flight unlock and dark tablet view stays usable',async({page})=>{
  const fixture=await fs.readFile('tests/fixtures/sealed-v1.writely','utf8');
  await page.setViewportSize({width:1024,height:768});await page.goto('/?mobile=1');
  await page.evaluate(text=>{localStorage.setItem('writely.sealed.workspace.v1',text);localStorage.setItem('writely.sealed.theme','dark');},fixture);await page.reload();
  await page.getByRole('button',{name:'Tresor entsperren',exact:true}).click();
  await page.getByLabel('Kennwort',{exact:true}).fill('Writely Testvektor Grüße 2026');
  await page.getByRole('button',{name:'Entsperren',exact:true}).click();
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,get:()=>true});document.dispatchEvent(new Event('visibilitychange'));});
  await expect(page.getByRole('button',{name:'Tresor entsperren',exact:true})).toBeVisible();
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,get:()=>false});document.dispatchEvent(new Event('visibilitychange'));});
  // A fresh unlock must wait for any cancelled KDF/storage transaction to end.
  await expect(page.getByRole('button',{name:'Tresor entsperren',exact:true})).toBeEnabled();
  expect(await page.locator('body').innerText()).not.toContain('Windows ↔ Android');
  await page.getByRole('button',{name:'Tresor entsperren',exact:true}).click();
  await page.getByLabel('Kennwort',{exact:true}).fill('Writely Testvektor Grüße 2026');
  await page.getByRole('button',{name:'Entsperren',exact:true}).click();
  await expect(page.locator('.secure-card')).toContainText('Windows ↔ Android');
  await page.getByRole('button',{name:'Datenschutz und Sicherheit',exact:true}).click();
  await page.getByLabel('Darstellung',{exact:true}).selectOption('dark');
  await page.getByRole('button',{name:'Datenschutz und Sicherheit',exact:true}).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
  await page.screenshot({path:'work/cross-platform/android-tablet-dark.png',fullPage:true});
});
